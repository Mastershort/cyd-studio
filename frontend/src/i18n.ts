let current: Record<Key, string> = de;
let currentLang: "de" | "en" = "de";

export function setLanguage(lang: string): void {
  currentLang = lang.startsWith("de") ? "de" : "en";
  current = currentLang === "de" ? de : en;
}

export function lang(): "de" | "en" {
  return currentLang;
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  let text = current[key] ?? key;
  for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

/** Display strings of the device (independent of the UI language). */
export function deviceStrings(language: string): Record<string, string> {
  const d = language === "en" ? en : de;
  return {
    on: d.state_on, off: d.state_off, open: d.state_open, closed: d.state_closed,
    opening: d.state_opening, closing: d.state_closing, locked: d.state_locked,
    unlocked: d.state_unlocked, unavailable: d.state_unavailable, unknown: "–",
  };
}

/** Pick the localized field of a data object (name / name_en). */
export function loc<T extends object>(obj: T, field: string): string {
  const o = obj as Record<string, unknown>;
  const value = currentLang === "en" ? o[`${field}_en`] ?? o[field] : o[field] ?? o[`${field}_en`];
  return String(value ?? "");
}

